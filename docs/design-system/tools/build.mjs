#!/usr/bin/env node
/*
 * Modified for Cherry OJ on 2026-09-03.
 * Deterministically generates the stable CSS entrypoint and machine token
 * snapshot from Foundation, the theme contract, and themes.manifest.json.
 * See ../NOTICE.md and ../LICENSE.open-design.
 */

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptFile = fileURLToPath(import.meta.url);
export const rootDir = path.resolve(path.dirname(scriptFile), "..");

async function readText(relativePath) {
  return readFile(path.join(rootDir, relativePath), "utf8");
}

async function readJson(relativePath) {
  return JSON.parse(await readText(relativePath));
}

export function parseCustomProperties(css) {
  const tokens = {};
  const declaration = /(--[a-zA-Z0-9-]+)\s*:\s*([^;]+);/g;
  for (const match of css.matchAll(declaration)) {
    tokens[match[1]] = match[2].replace(/\s+/g, " ").trim();
  }
  return tokens;
}

function parseFirstRootBlock(css) {
  const block = css.match(/:root\s*\{([\s\S]*?)\}/)?.[1];
  if (!block) throw new Error("tokens.foundation.css does not contain a :root block");
  return parseCustomProperties(block);
}

function generatedCss(themeManifest) {
  const imports = ["tokens.foundation.css", ...themeManifest.themes.map((theme) => theme.file)]
    .map((file) => `@import "./${file}";`)
    .join("\n");

  return `/*
 * GENERATED by tools/build.mjs. Do not edit directly.
 * Modified for Cherry OJ on 2026-09-03.
 * Productionized from the frozen Claude Design Cherry OJ source; includes a
 * semantic dual-theme contract, accessible interactions, and OJ states.
 * See NOTICE.md and LICENSE.open-design in this directory.
 */

${imports}
`;
}

function validateInputs(themeManifest, contract) {
  if (themeManifest.schemaVersion !== 1 || contract.schemaVersion !== 1) {
    throw new Error("theme manifest and contract schemaVersion must both be 1");
  }
  if (!Array.isArray(themeManifest.themes) || themeManifest.themes.length === 0) {
    throw new Error("themes.manifest.json must register at least one theme");
  }
  if (themeManifest.selectorAttribute !== "data-theme") {
    throw new Error("themes.manifest.json selectorAttribute must be data-theme");
  }
  const ids = new Set();
  const files = new Set();
  for (const theme of themeManifest.themes) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(theme.id)) throw new Error(`invalid theme id: ${theme.id}`);
    if (theme.file !== `themes/${theme.id}.css`) throw new Error(`${theme.id} file must be themes/${theme.id}.css`);
    if (!["dark", "light"].includes(theme.colorScheme)) throw new Error(`${theme.id} has invalid colorScheme`);
    if (typeof theme.label !== "string" || theme.label.trim().length === 0) throw new Error(`${theme.id} label must be non-empty`);
    if (typeof theme.provenance !== "string" || theme.provenance.trim().length === 0) {
      throw new Error(`${theme.id} provenance must be non-empty`);
    }
    if (ids.has(theme.id) || files.has(theme.file)) throw new Error(`duplicate theme id or file: ${theme.id}`);
    ids.add(theme.id);
    files.add(theme.file);
  }
  if (!ids.has(themeManifest.defaultTheme) || !ids.has(themeManifest.fallbackTheme)) {
    throw new Error("default and fallback theme ids must be registered");
  }
  if (themeManifest.themes[0].id !== themeManifest.defaultTheme) {
    throw new Error("default theme must be the first registered theme");
  }
}

async function generatedJson(themeManifest, contract) {
  const foundationFile = "tokens.foundation.css";
  const foundation = parseFirstRootBlock(await readText(foundationFile));
  const themes = [];

  for (const theme of themeManifest.themes) {
    themes.push({
      id: theme.id,
      label: theme.label,
      colorScheme: theme.colorScheme,
      version: theme.version,
      file: theme.file,
      provenance: theme.provenance,
      tokens: parseCustomProperties(await readText(theme.file))
    });
  }

  return `${JSON.stringify(
    {
      schemaVersion: 1,
      provenance: {
        ...themeManifest.provenance,
        contract: "theme-contract.json"
      },
      modified: {
        for: "Cherry OJ",
        date: "2026-09-03",
        summary: "Generated machine snapshot of the Claude Design-based Foundation and both production themes."
      },
      generated: {
        by: "tools/build.mjs",
        inputs: [foundationFile, "theme-contract.json", "themes.manifest.json", ...themeManifest.themes.map((theme) => theme.file)]
      },
      defaultTheme: themeManifest.defaultTheme,
      fallbackTheme: themeManifest.fallbackTheme,
      contractSchemaVersion: contract.schemaVersion,
      foundation: {
        file: foundationFile,
        tokens: foundation
      },
      themes
    },
    null,
    2
  )}\n`;
}

export async function generateOutputs() {
  const themeManifest = await readJson("themes.manifest.json");
  const contract = await readJson("theme-contract.json");
  validateInputs(themeManifest, contract);

  return {
    "tokens.css": generatedCss(themeManifest),
    "design-tokens.json": await generatedJson(themeManifest, contract)
  };
}

async function run() {
  const checkOnly = process.argv.slice(2).includes("--check");
  const outputs = await generateOutputs();
  const stale = [];

  for (const [relativePath, expected] of Object.entries(outputs)) {
    const absolutePath = path.join(rootDir, relativePath);
    if (checkOnly) {
      let actual = "";
      try {
        actual = await readFile(absolutePath, "utf8");
      } catch (error) {
        if (error?.code !== "ENOENT") throw error;
      }
      if (actual !== expected) stale.push(relativePath);
      continue;
    }

    await writeFile(absolutePath, expected, "utf8");
    console.log(`generated ${relativePath}`);
  }

  if (stale.length > 0) {
    throw new Error(`generated output is stale: ${stale.join(", ")}; run node tools/build.mjs`);
  }
  if (checkOnly) console.log("generated outputs are current");
}

const invokedFile = process.argv[1] ? path.resolve(process.argv[1]) : "";
if (invokedFile === scriptFile) {
  run().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
